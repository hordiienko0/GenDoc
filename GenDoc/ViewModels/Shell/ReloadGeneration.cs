namespace GenDoc.ViewModels.Shell
{
    /// <summary>
    /// Черговість перезавантажень, які запускають «і забувають» (`_ = ReloadAsync()`).
    ///
    /// Навіщо: зміна набору, пакета чи вузла дерева не чекає на попередній запит.
    /// Швидке перемикання лишало два запити в польоті, і повільніший приходив
    /// ОСТАННІМ - на екрані опинявся список попереднього вибору, тоді як комбо й
    /// дерево показували новий (аудит 2026-08-28).
    ///
    /// Скасувати сам запит нема чим - сервіси токена не приймають, - але й не
    /// треба: досить не застосовувати відповідь, що вже застаріла.
    ///
    /// Використання: `var token = _reload.Begin();` перед await, після await -
    /// `if (!_reload.IsCurrent(token)) return;` перед першим записом у стан в'юхи.
    /// </summary>
    public sealed class ReloadGeneration
    {
        private int _current;

        /// <summary>Починає нове перезавантаження й повертає його позначку.
        /// Усі попередні одразу стають застарілими.</summary>
        public int Begin() => Interlocked.Increment(ref _current);

        /// <summary>Чи це досі найсвіжіше перезавантаження. false - відповідь
        /// прийшла на вибір, якого користувач уже не робить.</summary>
        public bool IsCurrent(int token) => Volatile.Read(ref _current) == token;
    }
}
